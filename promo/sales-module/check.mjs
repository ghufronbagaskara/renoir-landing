import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {estimateDuration,opportunities} from './client.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const data=JSON.parse(await fs.readFile(path.join(root,'.work-capture/sales-module/data.json'),'utf8'));
assert.deepEqual(estimateDuration(1000,1,1,1),{median:19,slow:42});
assert.deepEqual(estimateDuration(2000,1,1,1),{median:38,slow:84});
for(const args of [[0,1,1,1],[-10,1,1,1],[1000,1.5,1,1],[NaN,1,1,1],[Infinity,1,1,1],[1e8,1,1,1],[1000,101,1,1]])assert.equal(estimateDuration(...args),null);
assert.deepEqual(estimateDuration(1000,0,0,0),{median:5,slow:12});
assert.deepEqual(opportunities([['Klien A','done','','','',''],['Klien B','cancel','done','','',''],['Klien C','','open','','','']],0),{never:[],cancelled:['Klien B']});
assert.equal(opportunities(data.klien,0).never.length,12);
assert.equal(opportunities(data.klien,0).cancelled.length,1);
assert.equal(data.status.reduce((s,row)=>s+row[1],0),80);
assert.equal(data.produk.reduce((s,row)=>s+row.j,0),59);
assert.equal(data.klien.length,36);assert.equal(data.tugas.length,8);assert.equal(data.soal.length,6);assert.equal(data.langkah.length,7);
assert(data.klien.every(row=>/^Klien \d{2}$/.test(row[0])));
const page=await fs.readFile(path.join(root,'public/resources/sales-playbook/index.html'),'utf8');
assert(!/proteksindo|fanos|isaac|munandar|[\u2013\u2014]/i.test(page));
assert(!/<script[^>]*\bsrc=|<link[^>]*\bhref=|\bonclick=/i.test(page));
assert.equal((page.match(/class="bab/g)||[]).length,10);
assert.equal((page.match(/data-task="/g)||[]).length,8);
assert(page.includes('65 kontrak')&&page.includes('66 catatan'));
assert(page.includes('Data simulasi')&&page.includes('./modul-sales.pdf'));
await fs.access(path.join(root,'public/resources/sales-playbook/modul-sales.pdf'));
console.log('Passed: estimator values and bounds, client filtering, data totals, anonymization, static content and local PDF link');
